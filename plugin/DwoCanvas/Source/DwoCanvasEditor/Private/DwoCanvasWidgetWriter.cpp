UWidgetBlueprint* FDwoCanvasWidgetWriter::LoadOrCreate(const FString& PackagePath, UClass* ParentClass, bool& bOutCreated, FString& OutError)
{
	bOutCreated = false;
	const FString AssetName = FPackageName::GetLongPackageAssetName(PackagePath);
	const FString ObjectPath = PackagePath + TEXT(".") + AssetName;

	if (FPackageName::DoesPackageExist(PackagePath))
	{
		UWidgetBlueprint* Existing = LoadObject<UWidgetBlueprint>(nullptr, *ObjectPath);
		if (!Existing)
		{
			OutError = FString::Printf(TEXT("%s exists but is not a Widget Blueprint"), *PackagePath);
		}
		return Existing;
	}

	if (!ParentClass || !ParentClass->IsChildOf(UUserWidget::StaticClass()))
	{
		OutError = FString::Printf(TEXT("Invalid parent class for %s"), *PackagePath);
		return nullptr;
	}

	UWidgetBlueprintFactory* Factory = NewObject<UWidgetBlueprintFactory>();
	Factory->ParentClass = ParentClass;
	Factory->BlueprintType = BPTYPE_Normal;

	IAssetTools& AssetTools = FModuleManager::LoadModuleChecked<FAssetToolsModule>("AssetTools").Get();
	UObject* Created = AssetTools.CreateAsset(AssetName, FPackageName::GetLongPackagePath(PackagePath), UWidgetBlueprint::StaticClass(), Factory);
	UWidgetBlueprint* Blueprint = Cast<UWidgetBlueprint>(Created);
	if (!Blueprint)
	{
		OutError = FString::Printf(TEXT("Could not create %s"), *PackagePath);
		return nullptr;
	}

	bOutCreated = true;
	return Blueprint;
}

void FDwoCanvasWidgetWriter::CloseEditors(UWidgetBlueprint* Blueprint)
{
	if (GEditor && Blueprint)
	{
		if (UAssetEditorSubsystem* AssetEditors = GEditor->GetEditorSubsystem<UAssetEditorSubsystem>())
		{
			AssetEditors->CloseAllEditorsForAsset(Blueprint);
		}
	}
}

bool FDwoCanvasWidgetWriter::HasDesignerContent(const UWidgetBlueprint* Blueprint)
{
	const UWidget* Root = Blueprint && Blueprint->WidgetTree ? Blueprint->WidgetTree->RootWidget.Get() : nullptr;
	if (!Root)
	{
		return false;
	}
	const UPanelWidget* RootPanel = Cast<UPanelWidget>(Root);
	return !RootPanel || RootPanel->GetChildrenCount() > 0;
}

void FDwoCanvasWidgetWriter::Discard(UObject* Object)
{
	if (Object)
	{
		Object->Rename(nullptr, GetTransientPackage(), REN_DontCreateRedirectors | REN_NonTransactional);
		Object->MarkAsGarbage();
	}
}

void FDwoCanvasWidgetWriter::ClearTree(UWidgetBlueprint* Blueprint)
{
	UWidgetTree* Tree = Blueprint->WidgetTree;
	TArray<UWidget*> OldWidgets;
	Tree->GetAllWidgets(OldWidgets);
	Tree->RootWidget = nullptr;

	for (UWidget* Widget : OldWidgets)
	{
		Discard(Widget);
	}

	// Regenerated by the compiler for the new widgets
	Blueprint->WidgetVariableNameToGuidMap.Empty();
}

UClass* FDwoCanvasWidgetWriter::GetNativeParent(const UWidgetBlueprint* Blueprint)
{
	UClass* Class = Blueprint ? Blueprint->ParentClass.Get() : nullptr;
	while (Class && !Class->HasAnyClassFlags(CLASS_Native))
	{
		Class = Class->GetSuperClass();
	}
	return Class;
}

TMap<FName, UClass*> FDwoCanvasWidgetWriter::GetBindWidgetProperties(const UClass* Class, bool bIncludeOptional)
{
	TMap<FName, UClass*> Result;
	if (!Class)
	{
		return Result;
	}
	for (TFieldIterator<FObjectPropertyBase> It(Class); It; ++It)
	{
		const bool bRequired = It->HasMetaData(TEXT("BindWidget"));
		const bool bOptional = It->HasMetaData(TEXT("BindWidgetOptional"));
		if (bRequired || (bIncludeOptional && bOptional))
		{
			Result.Add(It->GetFName(), It->PropertyClass);
		}
	}
	return Result;
}

void FDwoCanvasWidgetWriter::MarkBoundWidgetsAsVariables(UWidgetBlueprint* Blueprint)
{
	const TMap<FName, UClass*> Bound = GetBindWidgetProperties(GetNativeParent(Blueprint), true);
	Blueprint->WidgetTree->ForEachWidget([&Bound](UWidget* Widget)
	{
		Widget->SetFlags(RF_Transactional);
		Widget->bIsVariable = Bound.Contains(Widget->GetFName());
	});
}

bool FDwoCanvasWidgetWriter::Compile(UWidgetBlueprint* Blueprint, FString& OutError)
{
	FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);
	FKismetEditorUtilities::CompileBlueprint(Blueprint);
	if (Blueprint->Status == BS_Error)
	{
		OutError = FString::Printf(TEXT("%s did not compile"), *Blueprint->GetName());
		return false;
	}
	return true;
}

bool FDwoCanvasWidgetWriter::Save(UWidgetBlueprint* Blueprint, FString& OutError)
{
	if (!UEditorLoadingAndSavingUtils::SavePackages({ Blueprint->GetPackage() }, false))
	{
		OutError = FString::Printf(TEXT("%s could not be saved"), *Blueprint->GetName());
		return false;
	}
	return true;
}

bool FDwoCanvasWidgetWriter::CompileAndSave(UWidgetBlueprint* Blueprint, FString& OutError)
{
	return Compile(Blueprint, OutError) && Save(Blueprint, OutError);
}

UWidget* FDwoCanvasWidgetWriter::ConstructInTree(UWidgetBlueprint* Blueprint, UClass* WidgetClass, FName Name)
{
	UWidgetTree* Tree = Blueprint->WidgetTree;
	if (!WidgetClass)
	{
		return nullptr;
	}
	if (WidgetClass->IsChildOf(UUserWidget::StaticClass()))
	{
		return CreateWidget<UUserWidget>(Tree, WidgetClass, Name);
	}
	return NewObject<UWidget>(Tree, WidgetClass, Name, RF_Transactional);
}
